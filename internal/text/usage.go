// Usage explains the commands.
const Usage = `cleanpass — безпечна робота з копіями бази KeePassXC.

Використання:
  cleanpass compare <файл> [опції копії] [<файл> [опції копії]]...
      Показує паспорт кожної копії, відмінності, конфлікти, видалення, схожі записи,
      попередження і наступну команду. Секрети лишаються прихованими. Нічого не змінює на диску.
  cleanpass merge <файл> [опції копії] [<файл> [опції копії]]... --output <новий файл> [--allow-unrelated]
      Показує звіт, питає про конфлікти, видалення і схожі записи та зливає копії в новий файл.
      Оригінали не змінюються, наявний файл не перезаписується. За замовчуванням новий файл
      відкривають пароль, файл-ключ і YubiKey найновішої копії, але можна вибрати іншу копію або
      задати нові. Копії, схожі на різні бази, зупиняють злиття. Після -- кожне слово є файлом, тому
      опції стоять перед ним. Новий файл спершу перевіряє справжній KeePassXC, якщо він є на цій
      системі. Якщо його немає, команда про це попереджає.
  cleanpass status <файл> [опції копії] <файл> [опції копії]...
      Каже, чи копії однакові, яка відстає і чи вони розійшлись. Нічого не змінює на диску.
      Побайтно однакові файли не потребують пароля.
      Коди виходу: 0 однакові, 1 копія відстає (злиття не потрібне), 2 розійшлись, 3 помилка.

Опції копії стосуються файла перед ними:
  -k, --key-file <файл-ключ>   Файл-ключ для копії.
  -y, --yubikey <слот>         Слот YubiKey для копії: 1 або 2. Потрібна програма ykman від Yubico.

Інші опції:
  --allow-unrelated            Для merge: зливати навіть копії, схожі на різні бази.
  -h, --help                   Показати цю довідку.

Пароль:
  Майстер-пароль не передається через аргументи чи змінні середовища.
  З термінала він вводиться приховано, інакше читається рядками зі stdin.
  Enter повторює вже введений пароль. Після неправильного пароля є нова спроба. Нова спроба
  питає ще файл-ключ і слот YubiKey, тож у скрипті за паролем ідуть ще два рядки.
  Термінал mintty у Git Bash показував би пароль, тому тула відмовляється працювати в ньому:
  запускайте через winpty або у Windows Terminal. Скрипт із паролями в каналі працює.

Питання merge:
  Відповіді йдуть із термінала або рядками зі stdin після паролів. Відповідь це номер.
  Enter лишає питання без відповіді, і діє правило: запис лишається, новіша версія стає
  головною, схожі записи лишаються окремо, новий файл має ключі найновішої копії.
  с: більше не питати, для решти діють ті самі правила.
  п: показати значення одного поля. Воно лишиться в прокрутці термінала.
  Ctrl+C прибирає тимчасовий файл і повертає терміналу видимість введення.

YubiKey:
  Торкніться ключа, коли тула про це просить. Кожна копія з іншою сіллю потребує окремого дотику.
  Запис нового файла потребує ще одного, а перевірка справжнім KeePassXC — кількох: тула каже скількох.
  Формат KDBX 3 з YubiKey тула не відкриває.
`
